import pandas as pd
import numpy as np

print("--- [START] CHAPTER 3: TEMPORAL FEATURE ENGINEERING ENGINE ---")

# 1. Load the preprocessed master data from Chapter 2
preprocessed_file = 'tanesco_preprocessed_data.csv'
df = pd.read_csv(preprocessed_file)
print(f"[INFO] Loaded preprocessed historical data. Dimensions: {df.shape}")

# Initialize array to gather structured feature sets
engineered_rows = []

print("[PROCESS] Running sliding window parsing across 2,000 customer time-series profiles...")

# 2. Iterate through each customer to extract sliding sub-windows
for idx in range(len(df)):
    customer_id = df.iloc[idx]['Customer ID']

    # Isolate the 13 months of sequential consumption data
    full_series = [df.iloc[idx][f'Month_{m}'] for m in range(1, 14)]

    # Define three distinct 6-month historical windows out of the 13 available months
    # Window 1: M1-M6  | Window 2: M2-M7  | Window 3: M7-M12
    sub_windows = [
        {"history": full_series[0:6]},
        {"history": full_series[1:7]},
        {"history": full_series[6:12]}
    ]

    for window in sub_windows:
        months = window["history"]

        # A. Calculate 6-Month Rolling Mean
        rolling_avg = np.mean(months)

        # B. Calculate Volatility Index (Standard Deviation)
        volatility = np.std(months)

        # C. Calculate Regulatory Breach Frequency
        breach_freq = sum(1 for kwh in months if kwh > 75.0)

        # D. Calculate Abnormality Spike Factor
        # Compares the last month of the window against the mean of the previous 5 months
        prior_5_months_mean = np.mean(months[:-1]) if np.mean(months[:-1]) > 0 else 1.0
        spike_factor = months[-1] / prior_5_months_mean

        # E. Apply Regulatory Tariff Ground Truth Labeling
        # Target = 1 if the 6-month average breaks the 75 kWh constraint; otherwise 0
        target_label = 1 if rolling_avg > 75.0 else 0

        # Append all computed calculations into our final matrix
        engineered_rows.append({
            "Customer_ID": customer_id,
            "Rolling_Average_kWh": round(rolling_avg, 2),
            "Volatility_Index": round(volatility, 2),
            "Breach_Frequency": breach_freq,
            "Spike_Factor": round(spike_factor, 2),
            "Current_Month_Usage": round(months[-1], 2),
            "Target_Should_Shift": target_label
        })

# 3. Structuralize into a Machine Learning Feature Matrix DataFrame
ml_feature_matrix = pd.DataFrame(engineered_rows)

print("\n--- Feature Engineering Matrix Extraction Complete ---")
print(f"Final Feature Matrix Shape: {ml_feature_matrix.shape}")
print(f"Total Unique Samples Generated for AI Training: {ml_feature_matrix.shape[0]} rows.")

# Display statistical profile of our target vectors to inspect value distributions
