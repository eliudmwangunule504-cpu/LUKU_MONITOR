def apply_z_score_filter(history_months):
    Z_THRESHOLD = 0.85
    raw_array = np.array(history_months, dtype=float)
    mean_val = np.mean(raw_array)
    std_val = np.std(raw_array)

    if std_val == 0:
        return history_months

    smoothed = history_months.copy()
    for i in range(len(raw_array)):
        z_score = (raw_array[i] - mean_val) / std_val
        if z_score > Z_THRESHOLD:
            clipped_value = mean_val + (Z_THRESHOLD * std_val)
            smoothed[i] = round(clipped_value, 2)

    return smoothed

def calculate_custom_risk_score(rolling_avg):
    u = rolling_avg
    if u <= 15.0: p = 0.0 + (u / 15.0) * 0.10
    elif u <= 30.0: p = 0.11 + ((u - 15.0) / 15.0) * (0.20 - 0.11)
    elif u <= 45.0: p = 0.21 + ((u - 30.0) / 15.0) * (0.30 - 0.21)
    elif u <= 60.0: p = 0.31 + ((u - 45.0) / 15.0) * (0.40 - 0.31)
    elif u < 75.0: p = 0.41 + ((u - 60.0) / 15.0) * (0.49 - 0.41)
    elif u == 75.0: p = 0.51
    elif u <= 90.0: p = 0.51 + ((u - 75.0) / 15.0) * (0.60 - 0.51)
    elif u <= 105.0: p = 0.61 + ((u - 90.0) / 15.0) * (0.70 - 0.61)
    elif u <= 120.0: p = 0.71 + ((u - 105.0) / 15.0) * (0.80 - 0.71)
    elif u <= 135.0: p = 0.81 + ((u - 120.0) / 15.0) * (0.90 - 0.81)
    else:
        val = 0.91 + ((u - 135.0) / 15.0) * (1.00 - 0.91)
        p = min(val, 1.00)
    return p

