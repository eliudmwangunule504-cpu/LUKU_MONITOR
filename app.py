import pandas as pd
import numpy as np

def perform_tabular_augmentation(input_file, output_file, multiplication_factor=4):
    """
    Augments tabular time-series consumption data by cloning records and
    injecting controlled random noise to prevent model overfitting.
    """
    # 1. Load the original arranged dataset (500 customers)
    try:
        df_original = pd.read_csv(input_file)
        print(f"[INFO] Successfully loaded base dataset. Shape: {df_original.shape} (Customers: {df_original.shape[0]})")
    except FileNotFoundError:
        print(f"[ERROR] '{input_file}' not found. Please upload it to your Colab environment.")
        return None

    # Set a random seed for experimental reproducibility across runs
    np.random.seed(42)

    # Initialize our master batch list with the authentic baseline data
    augmented_batches = [df_original]
    base_count = len(df_original)

    # Determine how many clones we need to generate (Factor 4 means 1 base + 3 clones)
    num_clones_needed = multiplication_factor - 1

    print(f"[PROCESS] Generating {num_clones_needed} augmented variations via Stochastic Noise Injection...")

    # 2. Loop to create unique augmented clones
    for batch_idx in range(1, num_clones_needed + 1):
        cloned_df = df_original.copy()

        # Apply data augmentation across all consumption columns
        for col in cloned_df.columns:
            if col != 'Customer ID':
                # Generate uniform noise scaling factor between 0.95 and 1.05 (+/- 5% variation)
                # This ensures the synthetic customers have realistic, slight lifestyle deviations
                noise_multiplier = np.random.uniform(0.95, 1.05, size=len(cloned_df))

                # Multiply the original values by the noise and round to 2 decimal places
                cloned_df[col] = np.round(cloned_df[col] * noise_multiplier, 2)

        # 3. Handle Identity Generation (Prevent ID collision)
        # Shift Customer IDs sequentially (e.g., Customer 1 becomes Customer 501 in Batch 1)
        cloned_df['Customer ID'] = cloned_df['Customer ID'].apply(
            lambda x: f"Customer {int(x.split(' ')[1]) + (batch_idx * base_count)}"
        )

        # Append the mutated synthetic block to our collection
        augmented_batches.append(cloned_df)

    # 4. Concatenate all batches vertically into a unified dataframe
    final_augmented_df = pd.concat(augmented_batches, ignore_index=True)

    print("\n--- Augmentation Pipeline Complete ---")
    print(f"Final Expanded Shape: {final_augmented_df.shape}")
    print(f"Total Unique Customers: {final_augmented_df.shape[0]} (Target achieved!)")

    # Show a snapshot of the newly generated synthetic customer identities at the tail end
    print("\nTail Snapshot of Augmented Data Matrix:")
    print(final_augmented_df.tail(5))

    # 5. Export the large augmented dataset to disk
    final_augmented_df.to_csv(output_file, index=False)
    print(f"\n[SUCCESS] Augmented data securely saved as '{output_file}'!")

    return final_augmented_df

